# Ensure BASH_ENV is set for child bash processes even on images built before the
# Dockerfile ENV landed. start-infra persists this for login shells too.
ensure_bash_env_global() {
  export BASH_ENV="${DUST_SHELL_ENV_FILE}"

  if [ -f /root/.profile ] && ! grep -qF "BASH_ENV=${DUST_SHELL_ENV_FILE}" /root/.profile 2>/dev/null; then
    printf '\n# Dust materialized secrets for non-interactive bash\nexport BASH_ENV=%s\n' \
      "$DUST_SHELL_ENV_FILE" >>/root/.profile
  fi

  # Prepend a source hook for interactive bash that may not inherit Docker ENV.
  if [ -f /root/.bashrc ] && ! grep -qF "export BASH_ENV=${DUST_SHELL_ENV_FILE}" /root/.bashrc 2>/dev/null; then
    local tmp
    tmp="$(mktemp)"
    {
      printf '# Dust: ensure child bash processes load materialized secrets\n'
      printf 'export BASH_ENV=%s\n' "$DUST_SHELL_ENV_FILE"
      cat /root/.bashrc
    } >"$tmp"
    mv "$tmp" /root/.bashrc
  fi
}

# Fetch the full 1Password Environment once and persist it for all shells/commands.
# New secrets added in 1Password appear on the next materialize (start / refresh) with no script edits.
materialize_dev_environment() {
  write_shell_env_loader

  if require_op_credentials; then
    local tmp
    tmp="$(mktemp /tmp/dust-op-env.XXXXXX)"
    if ! op environment read "$OP_ENVIRONMENT_ID" >"$tmp"; then
      rm -f "$tmp"
      log "Failed to read 1Password environment $OP_ENVIRONMENT_ID"
      write_local_dev_env_file
      ensure_bash_env_global
      return 1
    fi
    chmod 600 "$tmp"
    mv "$tmp" "$DUST_OP_ENV_FILE"
    log "Materialized 1Password env ($(wc -l <"$DUST_OP_ENV_FILE" | tr -d ' ') vars) -> ${DUST_OP_ENV_FILE}"
  else
    log "Skipping 1Password materialize (credentials missing); local overrides only"
    rm -f "$DUST_OP_ENV_FILE"
  fi

  write_local_dev_env_file
  write_gcp_service_account_file
  ensure_bash_env_global
  return 0
}

# Source materialized env into the current shell (materialize first if missing).
load_op_environment() {
  if [ ! -f "$DUST_SHELL_ENV_FILE" ]; then
    materialize_dev_environment || return 1
  fi
  # shellcheck disable=SC1090
  source "$DUST_SHELL_ENV_FILE"
  return 0
}

export_op_runtime_secrets() {
  export DUST_REPO_ROOT="$DUST_REPO_ROOT"
  export SERVICE_ACCOUNT="${SERVICE_ACCOUNT:-}"
  export GCP_SERVICE_ACCOUNT="${GCP_SERVICE_ACCOUNT:-}"
  export DEV_WORKOS_USER_EMAIL="${DEV_WORKOS_USER_EMAIL:-}"
  export DEV_WORKOS_USER_PASSWORD="${DEV_WORKOS_USER_PASSWORD:-}"
  export DEV_WORKOS_USER_ID="${DEV_WORKOS_USER_ID:-}"
  # Local Cursor dev always uses in-container infra. 1Password envs often point at cloud
  # Postgres/Temporal/staging NODE_ENV which breaks init_plans, workers, and seed SQL.
  export NODE_ENV="development"
  export_local_dev_infra
}

# If env was already materialized (start-infra), pull it into any script that sources common.sh.
if [ -f "${DUST_SHELL_ENV_FILE:-/tmp/dust-shell-env.sh}" ] && [ -z "${DUST_SHELL_ENV_LOADING:-}" ] && [ -z "${DUST_COMMON_SKIP_SHELL_ENV:-}" ]; then
  # shellcheck disable=SC1090
  source "${DUST_SHELL_ENV_FILE:-/tmp/dust-shell-env.sh}"
fi
