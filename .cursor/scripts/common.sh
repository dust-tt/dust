#!/usr/bin/env bash
# Shared helpers for Dust Cloud Agent dev scripts.

DUST_REPO_ROOT="${DUST_REPO_ROOT:-$(
  cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd
)}"
export DUST_REPO_ROOT

DUST_INFRA_LOG_DIR="${DUST_INFRA_LOG_DIR:-/tmp/dust-infra}"
mkdir -p "$DUST_INFRA_LOG_DIR"

log() {
  echo "[${DUST_DEV_SCRIPT_NAME:-cursor-dev}] $*"
}

install_cursor_runtime_config() {
  if [ -f "${DUST_REPO_ROOT}/.cursor/config/mprocs.yaml" ]; then
    mkdir -p "${HOME}/.config/mprocs"
    cp "${DUST_REPO_ROOT}/.cursor/config/mprocs.yaml" "${HOME}/.config/mprocs/mprocs.yaml"
  fi
}

ensure_node_path() {
  if command -v node >/dev/null 2>&1; then
    return 0
  fi
  log "node not found on PATH"
  return 1
}

resolve_temporal_bin() {
  if command -v temporal >/dev/null 2>&1; then
    command -v temporal
    return 0
  fi
  for candidate in /usr/local/bin/temporal /root/.temporalio/bin/temporal; do
    if [ -x "$candidate" ]; then
      echo "$candidate"
      return 0
    fi
  done
  log "temporal CLI not found (rebuild .cursor/Dockerfile or install to /usr/local/bin)"
  return 1
}

# Migrations and seed scripts import @dust-tt/client (main: sdks/js/dist/index.js).
ensure_workspace_deps() {
  ensure_node_path
  cd "$DUST_REPO_ROOT"

  if [ ! -f node_modules/@dust-tt/client/package.json ]; then
    log "Installing npm workspaces (required before migrations)..."
    npm install
  fi

  if [ ! -f sdks/js/dist/index.js ]; then
    log "Building @dust-tt/client (sdks/js)..."
    npm -w @dust-tt/client run build
  fi
}

write_gcp_service_account_file() {
  if [ -n "${GCP_SERVICE_ACCOUNT:-}" ]; then
    printf '%s' "$GCP_SERVICE_ACCOUNT" >"${SERVICE_ACCOUNT:-/tmp/dust-dev-sa.json}"
    export SERVICE_ACCOUNT="${SERVICE_ACCOUNT:-/tmp/dust-dev-sa.json}"
  fi
}

# Materialized 1Password + local-dev env for every shell (see BASH_ENV / .cursor/bashrc).
# Prefer these over wrapping commands in `op run` (which masks TTY output and is easy to forget).
DUST_OP_ENV_FILE="${DUST_OP_ENV_FILE:-/tmp/dust-op-environment.env}"
DUST_LOCAL_ENV_FILE="${DUST_LOCAL_ENV_FILE:-/tmp/dust-local-dev.env}"
DUST_SHELL_ENV_FILE="${DUST_SHELL_ENV_FILE:-/tmp/dust-shell-env.sh}"

# `op environment read` requires 1Password CLI >= 2.33.0-beta.02 (Environments feature).
op_cli_supports_environments() {
  local current="${1:-$(op --version 2>/dev/null | head -1 | tr -d '[:space:]')}"
  local minimum="2.33.0-beta.02"

  if [ -z "$current" ]; then
    return 1
  fi

  # sort -V: if minimum sorts first, current is >= minimum.
  [ "$(printf '%s\n' "$minimum" "$current" | sort -V | head -1)" = "$minimum" ]
}

require_op_credentials() {
  if [ -z "${OP_SERVICE_ACCOUNT_TOKEN:-}" ]; then
    log "OP_SERVICE_ACCOUNT_TOKEN is not set (add it as a Cursor runtime secret)"
    return 1
  fi
  if [ -z "${OP_ENVIRONMENT_ID:-}" ]; then
    log "OP_ENVIRONMENT_ID is not set"
    return 1
  fi
  if ! op_cli_supports_environments; then
    log "op CLI is too old ($(op --version 2>/dev/null || echo unknown)); need >= 2.33.0-beta.02 with op environment read (rebuild .cursor/Dockerfile)"
    return 1
  fi
  return 0
}

# Escape a value for KEY=VALUE dotenv assignment (double-quoted).
dotenv_quote() {
  local value="${1-}"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//\$/\\\$}"
  value="${value//\`/\\\`}"
  printf '"%s"' "$value"
}

write_shell_env_loader() {
  cat >"$DUST_SHELL_ENV_FILE" <<EOF
# Auto-generated by Dust Cursor start scripts. Sourced via BASH_ENV and .cursor/bashrc.
# Secrets live in ${DUST_OP_ENV_FILE} / ${DUST_LOCAL_ENV_FILE}; this file only loads them.
if [ -n "\${DUST_SHELL_ENV_LOADING:-}" ]; then
  return 0 2>/dev/null || true
fi
DUST_SHELL_ENV_LOADING=1
_dust_bash_env_saved="\${BASH_ENV-}"
unset BASH_ENV

if [ -f "${DUST_OP_ENV_FILE}" ]; then
  set -a
  # shellcheck disable=SC1091
  . "${DUST_OP_ENV_FILE}"
  set +a
fi
if [ -f "${DUST_LOCAL_ENV_FILE}" ]; then
  set -a
  # shellcheck disable=SC1091
  . "${DUST_LOCAL_ENV_FILE}"
  set +a
fi

if [ -n "\${_dust_bash_env_saved}" ]; then
  export BASH_ENV="\${_dust_bash_env_saved}"
fi
unset _dust_bash_env_saved DUST_SHELL_ENV_LOADING
EOF
  chmod 644 "$DUST_SHELL_ENV_FILE"
}

